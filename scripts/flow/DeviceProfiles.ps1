function Get-ClaudeFlowStepInfo {
    [pscustomobject]@{ Name = 'DeviceProfiles'; Title = 'Device profiles'; DecisionKey = 'deviceProfiles'; DependsOn = @('Foundation'); Actions = @('Setup', 'Change', 'Guide') }
}

function Get-ClaudeFlowStepQuestions {
    param($Record, $Discovery)
    if (Get-ClaudeDecision -Record $Record -Key deviceProfiles) { return @() }
    @([pscustomobject]@{
        Key = 'deviceProfiles.conversationStorage'
        Question = 'Where should Claude Code conversation history live in the managed profile?'
        Options = @(
            New-ClaudeChoiceOption -Value 'local' -Label 'Local only' -Detail 'No roaming or central backup; simplest profile.' -Recommended -Reason 'least intrusive default'
            New-ClaudeChoiceOption -Value 'redirected' -Label 'Redirected' -Detail 'Requires a managed share or FSLogix-style path supplied when regenerating profiles.'
            New-ClaudeChoiceOption -Value 'audited' -Label 'Audited' -Detail 'Requires an OpenTelemetry collector and privacy review.'
        )
        AcceptRecommendedWithoutConsole = $true
    })
}

function Get-ClaudeFlowStepPlan {
    param($Record, $Discovery)
    New-ClaudeFlowPlan -Step DeviceProfiles -Summary 'Generate per-tier Claude Code and Desktop profiles' `
        -Actions @(
            New-ClaudeFlowAction -Verb Write -Target 'onboarding/profiles/standard'
            New-ClaudeFlowAction -Verb Write -Target 'onboarding/profiles/premium'
            New-ClaudeFlowAction -Verb Write -Target 'onboarding/profiles/README.md' -Detail 'developer handover note'
        ) `
        -Costs @() `
        -Implications @('Profiles include the recorded Desktop sign-in keys.', 'Assignment through Intune, Jamf or Group Policy remains an administrator task.') `
        -Requires @('The generated claude-gateway.json record') `
        -Rollback 'Delete onboarding/profiles and remove the MDM assignment'
}

function Invoke-ClaudeFlowStep {
    param($Record, $Plan)
    $root = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
    $policy = Join-Path $root 'scripts\New-ClaudeCodePolicy.ps1'
    if (-not (Test-Path -LiteralPath $policy)) { throw "Policy generator not found: $policy" }
    $recordPath = if ($Record.__recordPath) { $Record.__recordPath } else { Join-Path $root 'onboarding\claude-gateway.json' }
    if ($Record.tiers -and $Record.tiers.standard -and $Record.tiers.standard.PSObject.Properties.Name -contains 'models') {
        . (Join-Path $root 'scripts\ClaudeModelProfiles.ps1')
        $profiles = Write-ClaudeModelProfiles -Record $Record -RecordPath $recordPath
        return @{ deviceProfiles = $profiles }
    }
    $profileRoot = Join-Path (Split-Path $recordPath -Parent) 'profiles'
    New-Item -ItemType Directory -Path $profileRoot -Force | Out-Null
    $written = @()
    foreach ($tier in 'standard', 'premium') {
        $out = Join-Path $profileRoot $tier
        & $policy -ConfigPath $recordPath -Tier $tier -OutputPath $out | Out-Null
        $written += $out
    }
    $note = Join-Path $profileRoot 'README.md'
    @(
        '# Claude managed profiles'
        ''
        'Generated by Start-ClaudeGateway.ps1 from this deployment record.'
        ''
        '- `standard/` targets the standard entitlement tier.'
        '- `premium/` targets the premium entitlement tier.'
        '- Assign one profile route per device: Intune custom OMA-URI, Jamf mobileconfig, Group Policy registry, or the pilot apply script.'
        '- Desktop keys come from the recorded `desktopSignIn` choice; regenerate after changing that decision.'
        ''
        'Developer order: install or verify VS Code first, then the Claude Code CLI, then Claude Desktop.'
    ) | Set-Content -LiteralPath $note -Encoding UTF8
    @{ deviceProfiles = @{ generatedUtc = [DateTime]::UtcNow.ToString('o'); root = $profileRoot; tiers = @('standard', 'premium') } }
}

function Test-ClaudeFlowStep {
    param($Record)
    $root = $null
    $d = Get-ClaudeDecision -Record $Record -Key deviceProfiles
    if ($d -and $d.root) { $root = [string]$d.root }
    $checks = @()
    foreach ($tier in 'standard', 'premium') {
        $path = if ($root) { Join-Path $root $tier } else { '' }
        $checks += @{ Name = "$tier profile"; Passed = ($path -and (Test-Path -LiteralPath $path)); Evidence = $path; Fix = 'Run Start-ClaudeGateway.ps1 -Action Guide or Setup after the foundation step.' }
    }
    [pscustomobject]@{ Step = 'DeviceProfiles'; Passed = (@($checks | Where-Object { -not $_.Passed }).Count -eq 0); Checks = @($checks) }
}
